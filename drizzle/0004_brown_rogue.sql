CREATE FUNCTION originmetric_signup_workspace() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE ws uuid;
BEGIN
  INSERT INTO workspaces(name) VALUES (left(NEW.name, 200) || CASE WHEN length(NEW.name) < 190 THEN '''s workspace' ELSE '' END) RETURNING id INTO ws;
